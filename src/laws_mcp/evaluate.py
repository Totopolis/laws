"""Проверка поиска на контрольных запросах: dense, fts, hybrid и пересортировка.

    python -m laws_mcp.evaluate                              # три базовых режима
    python -m laws_mcp.evaluate onnx dense dense+rerank      # что даёт cross-encoder

Ожидаемый ответ у каждого запроса — «кодекс: номер статьи». Метрики — recall@k
и MRR (средняя обратная позиция первого правильного ответа).
"""
