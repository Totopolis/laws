# Реальные промахи, накопившиеся при работе: во всех норма сформулирована абстрактно
# («общие основания ответственности за причинение вреда»), а спрашивают о ней бытовым
# языком («сосед залил квартиру»). Именно на этом наборе виден смысл реранкера —
# на двух предыдущих recall уже упирается в 100%.
HARD = [
    ("сосед залил квартиру кто возмещает ущерб", ["gk-rf-chast-2:1064"]),
    ("ответственность за неуплату налога физическим лицом", ["nk-rf-chast-1:122"]),
    ("что такое юридическое лицо", ["gk-rf-chast-1:48"]),
    ("наследование по закону очередность", ["gk-rf-chast-3:1142"]),
    ("кто платит алименты на ребенка после развода", ["sk-rf:80"]),
    ("какой штраф если не заплатил налог вовремя", ["nk-rf-chast-1:122", "nk-rf-chast-1:75"]),
    ("собака покусала прохожего кто отвечает", ["gk-rf-chast-2:1064"]),
    ("работник сломал оборудование фирмы", ["tk-rf:238", "tk-rf:241"]),
]

CASES = SEMANTIC + TERMS + HARD


def evaluate(searcher, cases=CASES, top_k=10, modes=("dense", "fts", "hybrid")):
    """Режим «dense+rerank» — тот же dense, но с пересортировкой cross-encoder'ом."""
    stats = {}
    for mode in modes:
        hits, rr, misses = 0, 0.0, []
        for query, expected in cases:
            found = searcher.search(query, top_k=top_k, mode=mode.split("+")[0],
                                    rerank=mode.endswith("+rerank"))
            keys = [f"{h['code_slug']}:{h['article_number']}" for h in found]
            pos = next((i for i, k in enumerate(keys, 1) if k in expected), None)
            if pos:
                hits += 1
                rr += 1 / pos
            else:
                misses.append((query, expected[0], keys[:3]))
        n = len(cases)
        stats[mode] = dict(recall=hits / n, mrr=rr / n, misses=misses)
    return stats


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from .search import Searcher
    s = Searcher(backend=sys.argv[1] if len(sys.argv) > 1 else "auto")
    print(f"снапшот {s.date}, top-10\n")
    print(f"{'набор':<12} {'режим':<13} {'recall@10':>10} {'MRR':>8}")
    report = {}
    modes = sys.argv[2:] or ["dense", "fts", "hybrid"]
    for name, cases in (("смысловые", SEMANTIC), ("термины", TERMS), ("трудные", HARD)):
        report[name] = evaluate(s, cases, modes=modes)
        for mode, v in report[name].items():
            print(f"{name:<12} {mode:<13} {v['recall']:>10.0%} {v['mrr']:>8.3f}")
        print()
    last = modes[-1]                      # промахи показываем по последнему режиму
    for name, st in report.items():
        for q, exp, got in st[last]["misses"]:
            print(f"промах ({name}, {last}): «{q}» -> ждали {exp}, нашли {got}")


if __name__ == "__main__":
    main()
